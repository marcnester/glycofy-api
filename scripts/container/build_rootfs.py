"""Assemble a Python runtime, retaining Debian ownership metadata for scanning."""
from pathlib import Path
import json
import re
import shutil
import subprocess

root = Path("/runtime")
root.mkdir()
shutil.copytree("/usr/local", root / "usr/local", symlinks=True)
# These optional interpreter modules are not used by the PostgreSQL service.
# Remove their code as well as their native extensions, not scanner records.
stdlib = root / "usr/local/lib/python3.11"
for name in ("sqlite3", "idlelib", "tkinter", "turtledemo", "ensurepip", "curses"):
    shutil.rmtree(stdlib / name, ignore_errors=True)
for pattern in ("_sqlite3*", "_curses*", "readline*", "_tkinter*"):
    for path in (stdlib / "lib-dynload").glob(pattern):
        path.unlink()

copied = set()
def copy_file(source):
    source = Path(source)
    destination = root / source.relative_to("/")
    destination.parent.mkdir(parents=True, exist_ok=True)
    # Dereference links so the runtime has no dependency on omitted link targets.
    shutil.copy2(source, destination)
    copied.add(str(source))

copy_file("/bin/dash")
(root / "bin/sh").symlink_to("dash")

# Inspect all retained ELF objects, including bundled psycopg/crypto libraries.
for path in list((root / "usr/local").rglob("*")) + [root / "bin/dash"]:
    if not path.is_file() or path.is_symlink():
        continue
    with path.open("rb") as stream:
        if stream.read(4) != b"\x7fELF":
            continue
    # Use the source path so bundled libraries resolve their original RPATH.
    source = Path("/") / path.relative_to(root)
    result = subprocess.run(["ldd", str(source)], capture_output=True, text=True)
    if "not found" in result.stdout:
        raise RuntimeError(f"Unresolved runtime library: {source}: {result.stdout}")
    for dependency in re.findall(r"(?:=>\s+|^\s*)(/\S+)", result.stdout, re.MULTILINE):
        if not dependency.startswith("/usr/local/"):
            copy_file(dependency)

for path in ("/etc/ssl/certs/ca-certificates.crt", "/etc/os-release", "/etc/debian_version", "/etc/nsswitch.conf"):
    copy_file(path)
for name, content in {
    "passwd": "root:x:0:0:root:/root:/sbin/nologin\nglycofy:x:65532:65532:Glycofy:/app:/sbin/nologin\n",
    "group": "root:x:0:\nglycofy:x:65532:\n",
}.items():
    (root / "etc" / name).write_text(content)
(root / "tmp").mkdir(mode=0o1777)
(root / "tmp").chmod(0o1777)
(root / "app").mkdir()

# Keep the original package/version records for every Debian-owned copied file.
# dpkg itself is unnecessary at runtime; metadata remains available to Trivy/SBOM.
# CA bundle is generated by update-ca-certificates rather than listed in dpkg.
owners = {"ca-certificates", "tzdata"}
# Preserve timezone data used by workout reconciliation.
shutil.copytree("/usr/share/zoneinfo", root / "usr/share/zoneinfo", symlinks=True)
for path in sorted(copied):
    if path == "/etc/ssl/certs/ca-certificates.crt":
        continue
    candidates = {path, str(Path(path).resolve())}
    if path.startswith("/lib/"):
        candidates.add("/usr" + path)
    for candidate in candidates:
        result = subprocess.run(["dpkg-query", "-S", candidate], capture_output=True, text=True)
        if result.returncode == 0:
            owners.update(line.split(": ", 1)[0] for line in result.stdout.splitlines() if ": " in line)
            break
    else:
        raise RuntimeError(f"Missing package ownership for {path}")
status = subprocess.check_output(["dpkg-query", "-s", *sorted(owners)], text=True)
metadata = root / "var/lib/dpkg"
metadata.mkdir(parents=True)
(metadata / "status").write_text(status)
(root / "runtime-files.json").write_text(json.dumps({"debian_packages": sorted(owners), "debian_files": sorted(copied)}, indent=2))
print("Retained Debian packages:", sorted(owners))
